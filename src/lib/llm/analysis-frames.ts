/** 50 条框架的扁平视图：单测与「按编号定位」的口径都从这里取。 */
export function allAnalysisFrames(): string[] {
  return ANALYSIS_FRAME_CATEGORIES.flatMap((c) => c.frames);
}

/**
 * 拼成要附进系统 Prompt 的一段。开头的使用说明是本层加的调度纪律（任务书要求「AI 自动识别
 * 用户意图，调用对应的深度分析逻辑，不用用户选模板、不点按钮」），50 条框架本体一字不改。
 */
export function renderAnalysisFrames(): string {
  const total = allAnalysisFrames().length;
  const sections = ANALYSIS_FRAME_CATEGORIES.map((c) =>
    `### ${c.title}\n${c.frames.map((f, i) => `${i + 1}. ${f}`).join("\n")}`,
  ).join("\n\n");
  return [
    `【内置深度分析框架（共 ${total} 个）】`,
    "下面是本项目内置的 A 股深度研究提问框架。用户不会（也不需要）选择模板：你要根据用户的问题与当前上下文，",
    "自动判断最贴近的框架并以其分析路径展开深度回答；一次回答可合并多个框架的视角，但结构必须落在框架要求的问题上。",
    "界面不提供任何框架按钮，也不要向用户罗列这些编号让他们选。非行情类问题（生活/学习/写作）不套用本框架。",
    "",
    sections,
  ].join("\n");
}
