/**
 * P28 稳智对齐：自动检测交易周期（resolveTradingHorizonForInput）。
 * 稳智的 resolveTradingHorizonForInput 用正则匹配用户输入，命中直接进 payload，未命中返回 null。
 * 本仓库实现同一逻辑：正则匹配"超短"/"1天"/"短线"/"波段"/"中长期"/"长线"等关键词。
 */
export function resolveTradingHorizonForInput(input: string): ChatHorizon | null {
  if (!input || typeof input !== "string") return null;
  const t = input.toLowerCase();
  
  // 超短：1 天以内（日内/隔夜）
  if (/超短|日内|隔夜|打板|t\+0|1\s*天|一天/.test(t)) return "ultrashort";
  
  // 短线：1-3 天
  if (/短线|1\s*到\s*3\s*天|2\s*天|三天|3\s*天|两三\s*天/.test(t)) return "short";
  
  // 短中：3-5 天
  if (/短中|3\s*到\s*5\s*天|四\s*天|五天|5\s*天|三四\s*天/.test(t)) return "shortmid";
  
  // 中线：5-20 天（1-4 周）
  if (/中线|波段|1\s*到\s*4\s*周|2\s*周|三\s*周|4\s*周|一个月|20\s*天|1\s*月/.test(t)) return "mid";
  
  // 长线：20 天以上（1 个月+）
  if (/长线|长期|中长期|1\s*个月|半年|一年|长期持有/.test(t)) return "long";
  
  return null;
}
