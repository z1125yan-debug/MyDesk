// 新闻解读（确定性规则，不调模型）：给能解释的新闻标题跟一句自然的解释。
//
// 口径（用户 2026-10-17 定）：
// 1. 解释直接跟在新闻后面，不加“解读：”标签，不加“解读：偏利空——原因”这种机械格式；
//    方向自然写进句子里（“……偏利好。”/“……偏利空。”）。
// 2. 分析不出来的返回 null，调用方只留新闻本身，不追加任何填充句（不写“不明确”之类）。
// 3. 停牌 ≠ 退市：标题含“停牌”时只说临时停牌，绝不映射成“退出市场”；分不清方向就不写方向。
// 4. 程序性/流程类标题（备案、开会、披露等）没有实质解释可给 → null，不硬编。

/** 标题 → 一句自然解释；分析不出来 → null（调用方只留新闻本身）。 */
export function interpretNewsTitle(title: string): string | null {
  const t = String(title ?? "");
  // 停牌守卫（优先于一切）：停牌是临时停牌，不是退市。
  if (t.includes("停牌")) {
    if (t.includes("复牌")) return "股票停牌后复牌，恢复交易。";
    return "股票临时停牌，复牌前不能交易。";
  }
  if (t.includes("复牌")) return "股票复牌，恢复交易。";
  // 长词例外优先：“成本调查”是行业摸底，不是公司被调查，不能被泛化的“调查”抢先误判。
  if (t.includes("成本调查")) return "这是行业成本摸底，不是公司被调查。";
  // 业绩预告 / 快报但标题没说预增还是预减 → 方向在公告正文里，不硬猜 → null。
  if (/业绩预告|业绩快报/.test(t) && !/预增|预减|扭亏|预亏|亏损|盈利|增长|下滑/.test(t)) {
    return null;
  }
  // 豁免 / 解除 / 取消 + 制裁 / 限制 / 关税 = 利好（先于单关键词“制裁”判）。
  if (/豁免|解除|取消/.test(t) && /制裁|限制|关税/.test(t)) {
    return "限制被取消，压力减轻，偏利好。";
  }
  const hit = (table: Record<string, string>): string | null => {
    for (const k of Object.keys(table)) if (t.includes(k)) return k;
    return null;
  };
  const bear = hit(BEARISH);
  const bull = hit(BULLISH);
  // 利好与利空混在一起 → 分不清，不写。
  if (bear && bull) return null;
  if (bear) return BEARISH[bear];
  if (bull) return BULLISH[bull];
  return null;
}

