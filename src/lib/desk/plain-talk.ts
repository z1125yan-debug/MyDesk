  "1. 读者是不看盘的普通人。任何专业词第一次出现时，当场用半句人话解释它——形式是「术语，也就是……」或直接换成人话；同一个词后面再出现就不用重复解释了。",
  "2. 高频黑话对照（照这个意思翻，不要照抄术语）：",
  "   · 量比 → 今天到现在成交的量，比最近几天同一时间放大了多少倍",
  "   · 换手率 → 今天有多少比例的流通股换了主人（越高说明分歧越大、筹码越松）",
  "   · 委比 / 五档 → 挂在盘口等着成交的买单厚还是卖单厚",
  "   · 内外盘 → 是主动往卖价上打的多，还是主动往买价上砸的多",
  "   · 主力净额 → 按单笔成交金额分档粗算出来的「大单净买入」，是统计口径，不等于有庄、也不等于聪明钱",
