/**
 * 【说人话】去黑话口径。
 *
 * 三条硬要求：
 *  1. 专业词第一次出现必须当场翻译成人话（给一份高频黑话替换表——实测只说「避免术语」
 *     模型不知道该换成什么，给替换对照它才照做）；
 *  2. 术语不能当结论：「量能不足」「情绪退潮」「分歧转一致」这类词单独出现等于什么都没说，
 *     必须接一句「也就是说，接下来更可能怎样、你怎么看出来」；
 *  3. 有些词根本无法验证（情绪/分歧/承接/修复/退潮/主力意图），不许拿它们当论据，
 *     只允许在已经摆出可观察数字之后当**总结性的形容词**用一次。
 */
